#!/usr/bin/env node
// Builds supabase/setup.sql: every migration in order, then the seed content,
// as ONE file to paste into the Supabase SQL Editor. Safe to run again: every
// step either creates what is missing or updates what is there.
//
//   npm run db:setup-sql      (also rebuilds seed.sql first)

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const DIR = new URL('../supabase/', import.meta.url);
const migrations = readdirSync(new URL('migrations/', DIR)).filter((f) => f.endsWith('.sql')).sort();
let sql = `-- Bible Trivia: complete database setup.
-- Generated by scripts/build-setup-sql.mjs. Do not edit; edit supabase/migrations/ instead.
-- Paste this whole file into Supabase → SQL Editor → Run. Running it again is safe.
-- Afterwards, load the ~17,000 Recall questions with: npm run db:import

`;
for (const f of migrations) {
  sql += `\n-- ======================================================================\n-- ${f}\n-- ======================================================================\n`;
  sql += readFileSync(new URL(`migrations/${f}`, DIR), 'utf8');
}
sql += `\n-- ======================================================================\n-- seed.sql (books, starter questions, verses, gospel, FAQ)\n-- ======================================================================\n`;
sql += readFileSync(new URL('seed.sql', DIR), 'utf8');
// Make PostgREST notice the new functions and columns straight away.
sql += `\nnotify pgrst, 'reload schema';\n`;
writeFileSync(new URL('setup.sql', DIR), sql);
console.log(`wrote supabase/setup.sql: ${migrations.length} migrations + seed (${Math.round(sql.length / 1024)} KB)`);
