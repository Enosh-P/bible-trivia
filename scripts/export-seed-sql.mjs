// Turns the 66 books and the JSON question packs into supabase/seed.sql.
// Re-running is safe: rows are upserted.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const lit = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replaceAll("'", "''")}'`);
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;

// Books: parse the table straight out of src/i18n/books.ts so there is one source of truth.
const booksSrc = readFileSync(new URL('src/i18n/books.ts', root), 'utf8');
const rows = [...booksSrc.matchAll(/\['([0-9A-Z]{3})', '([^']+)', '([^']+)'\]/g)];
if (rows.length !== 66) throw new Error(`expected 66 books, found ${rows.length}`);

let sql = '-- Generated by scripts/export-seed-sql.mjs — do not edit by hand.\nbegin;\n\n';
sql += 'insert into books (code, position, testament, name_en, name_ta) values\n';
sql += rows
  .map(([, code, en, ta], i) => `  (${lit(code)}, ${i + 1}, ${lit(i < 39 ? 'OT' : 'NT')}, ${lit(en)}, ${lit(ta)})`)
  .join(',\n');
sql += '\non conflict (code) do update set name_en = excluded.name_en, name_ta = excluded.name_ta;\n\n';

const packDir = new URL('content/packs/', root);
let count = 0;
for (const file of readdirSync(packDir).filter((f) => f.endsWith('.json'))) {
  const pack = JSON.parse(readFileSync(new URL(file, packDir), 'utf8'));
  sql += `-- ${file}\n`;
  for (const q of pack.questions) {
    sql +=
      `insert into questions (id, type, book_code, chapter, verse, verse_end, difficulty, answer, en, ta, art, tags, status) values (` +
      [lit(q.id), lit(q.type), lit(q.book), q.chapter, q.verse ?? 'null', q.verseEnd ?? 'null', q.difficulty, json(q.answer), json(q.en), json(q.ta), lit(q.art), `array[${(q.tags ?? []).map(lit).join(',')}]::text[]`, "'published'"].join(', ') +
      `)\n  on conflict (id) do update set type = excluded.type, book_code = excluded.book_code, chapter = excluded.chapter, verse = excluded.verse, verse_end = excluded.verse_end, difficulty = excluded.difficulty, answer = excluded.answer, en = excluded.en, ta = excluded.ta, art = excluded.art, tags = excluded.tags, updated_at = now();\n`;
    count++;
  }
  sql += '\n';
}
// Verses, gospel steps, FAQ
const verses = JSON.parse(readFileSync(new URL('content/verses.json', root), 'utf8')).verses;
sql += '-- verses\n';
for (const v of verses) {
  sql += `insert into verses (id, book_code, chapter, verse, en, ta) values (${[lit(v.id), lit(v.book), v.chapter, v.verse, lit(v.en), lit(v.ta)].join(', ')})\n  on conflict (id) do update set en = excluded.en, ta = excluded.ta, updated_at = now();\n`;
}
const gospel = JSON.parse(readFileSync(new URL('content/gospel.json', root), 'utf8'));
const arr = (xs) => `array[${xs.map(lit).join(',')}]::text[]`;
sql += '\n-- reading sources\n';
for (const s of gospel.sources) {
  sql += `insert into reading_sources (id, author, title) values (${lit(s.id)}, ${json(s.author)}, ${lit(s.title)}) on conflict (id) do update set author = excluded.author, title = excluded.title;\n`;
}
sql += '\n-- gospel steps (positions cleared first so re-ordering works)\nupdate gospel_steps set position = position + 1000;\n';
gospel.steps.forEach((st, i) => {
  sql += `insert into gospel_steps (id, position, icon, horse, title, body, prayer, next, verse_ids) values (${[lit(st.id), i + 1, lit(st.icon), lit(st.horse), json(st.title), json(st.body), st.prayer ? json(st.prayer) : 'null', st.next ? json(st.next) : 'null', arr(st.verses)].join(', ')})\n  on conflict (id) do update set position = excluded.position, icon = excluded.icon, horse = excluded.horse, title = excluded.title, body = excluded.body, prayer = excluded.prayer, next = excluded.next, verse_ids = excluded.verse_ids;\n`;
});
sql += '\n-- faqs\nupdate faqs set position = position + 1000;\n';
gospel.faqs.forEach((f, i) => {
  sql += `insert into faqs (id, position, q, a, verse_ids, reading_ids) values (${[lit(f.id), i + 1, json(f.q), json(f.a), arr(f.verses), arr(f.reading)].join(', ')})\n  on conflict (id) do update set position = excluded.position, q = excluded.q, a = excluded.a, verse_ids = excluded.verse_ids, reading_ids = excluded.reading_ids;\n`;
});
sql += '\ncommit;\n';

writeFileSync(new URL('supabase/seed.sql', root), sql);
console.log(`wrote supabase/seed.sql: 66 books, ${count} questions, ${verses.length} verses, ${gospel.steps.length} gospel steps, ${gospel.faqs.length} FAQs`);
